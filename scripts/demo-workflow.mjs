console.log('CHANGE:',change.title);
console.log('DOWNSTREAM IMPACTS:',change.impacts.length);
for(const impact of change.impacts)console.log(' -',impact.path.map(id=>project.tasks.find(t=>t.id===id).title).join(' -> '));
